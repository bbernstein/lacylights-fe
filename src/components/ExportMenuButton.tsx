'use client';

import { Fragment, useCallback, useEffect, useId, useState } from 'react';
import Link from 'next/link';
import { useApolloClient } from '@apollo/client';
import {
  ArrowDownTrayIcon,
  ArrowsUpDownIcon,
  ChevronDownIcon,
  DocumentTextIcon,
  TableCellsIcon,
} from '@heroicons/react/24/outline';
import {
  DataExportFormat,
  DataExportTable,
  buildDataExportPageHref,
  exportAndDownloadDataTable,
  formatErrorMessage,
  isProjectOptional,
} from '@/lib/importExport';

/** One exportable table in the menu, with a heading when there are several. */
export interface ExportMenuTable {
  table: DataExportTable;
  /** Group heading, e.g. "Fixture types" (shown when the menu has several tables). */
  label: string;
  /** Look / cue list / look board id for scoped tables. */
  scopeId?: string | null;
}

export interface ExportMenuButtonProps {
  /** Table to export. Use `tables` instead to offer several tables in one menu. */
  table?: DataExportTable;
  /** Several tables in one menu (e.g. Fixtures and Fixture types). */
  tables?: ReadonlyArray<ExportMenuTable>;
  /** Look / cue list / look board id for a scoped `table`. */
  scopeId?: string | null;
  /** Project to export from. Not needed for FIXTURE_LIBRARY. */
  projectId?: string | null;
  /**
   * `default` matches the light/dark page header buttons; `toolbar` matches
   * the always-dark editor toolbars (look editor, cue list player).
   */
  appearance?: 'default' | 'toolbar';
  /** Hide the "Export" text below the `sm` breakpoint (icon + chevron only). */
  compact?: boolean;
  /** Extra classes for the wrapper element. */
  className?: string;
}

const FORMAT_ITEMS: ReadonlyArray<{ format: DataExportFormat; label: string; icon: typeof DocumentTextIcon }> = [
  { format: DataExportFormat.Csv, label: 'CSV', icon: DocumentTextIcon },
  { format: DataExportFormat.Xlsx, label: 'Excel', icon: TableCellsIcon },
];

const BUTTON_CLASSES: Record<NonNullable<ExportMenuButtonProps['appearance']>, string> = {
  default:
    'inline-flex items-center gap-1.5 px-3 py-2 min-h-[44px] sm:min-h-0 border border-gray-300 dark:border-gray-600 rounded-md shadow-sm text-sm font-medium text-gray-700 dark:text-gray-300 bg-white dark:bg-gray-700 hover:bg-gray-50 dark:hover:bg-gray-600 focus:outline-none focus:ring-2 focus:ring-offset-2 focus:ring-blue-500 disabled:opacity-50 disabled:cursor-not-allowed touch-manipulation',
  toolbar:
    'inline-flex items-center gap-1.5 px-3 py-2 text-sm font-medium text-gray-300 hover:text-white bg-gray-700 hover:bg-gray-600 rounded-md transition-colors disabled:opacity-50 disabled:cursor-not-allowed touch-manipulation',
};

/**
 * "Export ▾" button for list and detail pages. The menu offers CSV and
 * Excel downloads of the page's data (generated by the server) and a link
 * to the Import / Export page with the same context preselected.
 */
export default function ExportMenuButton({
  table,
  tables,
  scopeId,
  projectId,
  appearance = 'default',
  compact = false,
  className = '',
}: ExportMenuButtonProps) {
  const client = useApolloClient();
  const menuId = useId();
  const [open, setOpen] = useState(false);
  const [busyKey, setBusyKey] = useState<string | null>(null);
  const [error, setError] = useState<string | null>(null);

  const items: ReadonlyArray<ExportMenuTable> =
    tables && tables.length > 0 ? tables : table ? [{ table, label: '', scopeId }] : [];
  const showHeadings = items.length > 1;
  const primary = items[0];

  const close = useCallback(() => {
    setOpen(false);
    setError(null);
  }, []);

  // Close on Escape.
  useEffect(() => {
    if (!open) return;
    const onKey = (e: KeyboardEvent) => {
      if (e.key === 'Escape') close();
    };
    document.addEventListener('keydown', onKey);
    return () => document.removeEventListener('keydown', onKey);
  }, [open, close]);

  const canExport = (item: ExportMenuTable) => isProjectOptional(item.table) || !!projectId;

  const handleExport = async (item: ExportMenuTable, format: DataExportFormat) => {
    const key = `${item.table}:${format}`;
    setBusyKey(key);
    setError(null);
    try {
      await exportAndDownloadDataTable(client, {
        table: item.table,
        format,
        projectId: isProjectOptional(item.table) ? projectId || null : projectId,
        scopeId: item.scopeId ?? null,
      });
      setOpen(false);
    } catch (err) {
      setError(formatErrorMessage(err, 'Export failed.'));
    } finally {
      setBusyKey(null);
    }
  };

  if (!primary) return null;

  const moreHref = buildDataExportPageHref({
    table: primary.table,
    scopeId: primary.scopeId,
    projectId: isProjectOptional(primary.table) ? null : projectId,
  });

  return (
    <div className={`relative inline-block text-left ${className}`}>
      <button
        type="button"
        onClick={() => (open ? close() : setOpen(true))}
        className={BUTTON_CLASSES[appearance]}
        aria-haspopup="menu"
        aria-expanded={open}
        aria-controls={open ? menuId : undefined}
        aria-label="Export"
        title="Export as CSV or Excel"
      >
        <ArrowDownTrayIcon className="h-4 w-4" aria-hidden="true" />
        <span className={compact ? 'hidden sm:inline' : ''}>Export</span>
        <ChevronDownIcon
          className={`h-4 w-4 transition-transform ${open ? 'rotate-180' : ''}`}
          aria-hidden="true"
        />
      </button>

      {open && (
        <>
          {/* Backdrop: closes the menu on outside click / tap. */}
          <div className="fixed inset-0 z-40" onClick={close} aria-hidden="true" data-testid="export-menu-backdrop" />
          <div
            id={menuId}
            role="menu"
            aria-label="Export options"
            className="absolute right-0 top-full mt-1 z-50 min-w-[220px] max-w-[calc(100vw-2rem)] bg-white dark:bg-gray-800 rounded-lg shadow-lg border border-gray-200 dark:border-gray-700 py-1"
          >
            {items.map((item, idx) => (
              <Fragment key={item.table}>
                {showHeadings && (
                  <div
                    className={`px-4 pt-2 pb-1 text-xs font-semibold uppercase tracking-wide text-gray-500 dark:text-gray-400 ${
                      idx > 0 ? 'border-t border-gray-200 dark:border-gray-700 mt-1' : ''
                    }`}
                    role="presentation"
                  >
                    {item.label}
                  </div>
                )}
                {FORMAT_ITEMS.map(({ format, label, icon: Icon }) => {
                  const key = `${item.table}:${format}`;
                  const disabled = busyKey !== null || !canExport(item);
                  return (
                    <button
                      key={key}
                      type="button"
                      role="menuitem"
                      disabled={disabled}
                      aria-disabled={disabled}
                      aria-label={showHeadings ? `${item.label} as ${label}` : label}
                      onClick={() => handleExport(item, format)}
                      className="w-full text-left px-4 py-3 sm:py-2 hover:bg-gray-100 dark:hover:bg-gray-700 flex items-center gap-2 text-sm text-gray-700 dark:text-gray-200 transition-colors disabled:opacity-50 disabled:cursor-not-allowed touch-manipulation"
                    >
                      <Icon className="h-4 w-4 shrink-0" aria-hidden="true" />
                      <span>{busyKey === key ? 'Exporting...' : label}</span>
                    </button>
                  );
                })}
              </Fragment>
            ))}

            <div className="border-t border-gray-200 dark:border-gray-700 my-1" role="separator" />
            <Link
              href={moreHref}
              role="menuitem"
              onClick={() => setOpen(false)}
              className="w-full text-left px-4 py-3 sm:py-2 hover:bg-gray-100 dark:hover:bg-gray-700 flex items-center gap-2 text-sm text-gray-700 dark:text-gray-200 transition-colors touch-manipulation"
            >
              <ArrowsUpDownIcon className="h-4 w-4 shrink-0" aria-hidden="true" />
              <span>More import/export options…</span>
            </Link>

            {error && (
              <div
                role="alert"
                className="mx-2 my-1 p-2 rounded border border-red-300 dark:border-red-700 bg-red-50 dark:bg-red-900/20 text-xs text-red-700 dark:text-red-300"
              >
                {error}
              </div>
            )}
          </div>
        </>
      )}
    </div>
  );
}
